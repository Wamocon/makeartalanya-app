export type Locale = "en" | "tr" | "ru";

/** Client-side locale reader */
export function getClientLocale(): Locale {
  if (typeof document === "undefined") return "en";
  const match = document.cookie.match(/(?:^|; )lang=([^;]*)/);
  const lang = match?.[1];
  if (lang === "tr" || lang === "ru") return lang;
  return "en";
}

